"""
SentinelX Live Traffic Monitor

This script reads network traffic flows from a CSV in real-time (as generated by cicflowmeter)
and evaluates them against our 3 detection engines (GraphSAGE, Rule Engine, Isolation Forest).

Usage:
  # Real mode (Ubuntu running cicflowmeter)
  python live_monitor.py --file live_traffic.csv
  
  # Simulator mode (Local testing on existing dataset)
  python live_monitor.py --simulate --file "../dataset/combinenew.csv"
"""

