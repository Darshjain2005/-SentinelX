# CLI Colors using ANSI
class Colors:
    RED = '\033[91m'
    GREEN = '\033[92m'
    YELLOW = '\033[93m'
    CYAN = '\033[96m'
    BOLD = '\033[1m'
    RESET = '\033[0m'

def print_alert(flow_idx, msg, engine, severity="HIGH"):
    print(f"\n{Colors.RED}{Colors.BOLD}[!] ALERT TRIGGERED {Colors.RESET}")
    print(f"{Colors.RED} > Flow #   : {flow_idx}{Colors.RESET}")
    print(f"{Colors.RED} > Engine   : {engine}{Colors.RESET}")
    print(f"{Colors.RED} > Details  : {msg}{Colors.RESET}")
    print(f"{Colors.RED} > Severity : {severity}{Colors.RESET}")
    print("-" * 60)

def load_engines():
    print(f"{Colors.CYAN}[*] Loading SentinelX Detection Engines...{Colors.RESET}")
    
    # 1. Rule Engine
    rules_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'detection_engine', 'rules')
    rule_engine = RuleEngine(rules_dir)
    print(f"    - Rule Engine Loaded ({len(rule_engine.rules)} rules)")
    
    # 2. Isolation Forest (We'll load a quick pretrained one or mock it for demo if not saved)
    # Since we didn't save the IF model in the previous script to a file, 
    # we will initialize a fresh one and train it on a tiny random background set on startup.
    print(f"    - Initializing Isolation Forest... (training on background traffic)")
    if_detector = AnomalyDetector(contamination=0.05)
    
    # Let's load 1000 rows of background traffic to train IF and use for GraphSAGE context
    dataset_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'dataset', 'combinenew.csv')
    df_bg = pd.read_csv(dataset_path, nrows=2000, low_memory=False)
    df_bg.columns = df_bg.columns.str.strip()
    
    # Train IF on background
    if_detector.train(df_bg)
    
    # 3. GraphSAGE
    print(f"    - Loading GraphSAGE Model...")
    drop_cols = ["Label", "BinaryLabel"]
    feature_cols = [c for c in df_bg.columns if c not in drop_cols]
    
    # Calculate global mean/std for scaling (simplified for demo)
    X_bg_raw = df_bg[feature_cols].replace([np.inf, -np.inf], np.nan).fillna(0).values.astype(np.float32)
    scaler_mean = np.mean(X_bg_raw, axis=0)
    scaler_std = np.std(X_bg_raw, axis=0) + 1e-8
    
    # Keep 50 scaled background nodes to build the KNN graph against incoming live traffic
    X_bg_scaled = (X_bg_raw[:50] - scaler_mean) / scaler_std
    y_bg = (df_bg["Label"].astype(str).str.strip().values[:50] != "BENIGN").astype(np.int64)
    
    gs_model = GraphSAGEDetector(in_channels=X_bg_scaled.shape[1])
    try:
        gs_model.load_state_dict(torch.load(GRAPHSAGE_MODEL_PATH, map_location=torch.device('cpu'), weights_only=True))
        gs_model.eval()
        print(f"    - GraphSAGE Loaded successfully.")
    except Exception as e:
        print(f"{Colors.YELLOW}[!] Warning: Could not load GraphSAGE model from {GRAPHSAGE_MODEL_PATH}. Was it trained?{Colors.RESET}")
    
    return rule_engine, if_detector, gs_model, X_bg_scaled, y_bg, scaler_mean, scaler_std, feature_cols

def follow(thefile):
    """Generator that yields new lines in a file like 'tail -f'"""
    thefile.seek(0, 2)
    while True:
        line = thefile.readline()
        if not line:
            time.sleep(0.1)
            continue
        yield line

def simulate_live_feed(filepath, max_rows=200):
    """Simulate live traffic from a CSV. Picks a smart mix of BENIGN + Attack rows."""
    import random
    random.seed(42)
    
    with open(filepath, 'r', encoding='utf-8') as f:
        header = f.readline()
        yield header
        all_lines = f.readlines()
    
    # Pick ~140 BENIGN + ~60 attack rows (to make the demo interesting)
    benign_lines = [l for l in all_lines if l.rstrip().endswith('BENIGN')]
    attack_lines = [l for l in all_lines if not l.rstrip().endswith('BENIGN')]
    
    n_benign = min(140, len(benign_lines))
    n_attack = min(60, len(attack_lines))
    
    selected = random.sample(benign_lines, n_benign) + random.sample(attack_lines, n_attack)
    random.shuffle(selected) # Mix them up
    
    print(f"{Colors.CYAN}[i] Simulator: feeding {len(selected)} flows ({n_benign} benign + {n_attack} attack){Colors.RESET}")
    for line in selected[:max_rows]:
        time.sleep(0.08)  # 80ms per flow
        yield line

