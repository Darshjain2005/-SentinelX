                # Prepare features for ML
                x_live = np.array([features_raw], dtype=np.float32)
                x_live[np.isinf(x_live)] = 0
                
                # 2. Isolation Forest Evaluation (suppress prints)
                df_live = pd.DataFrame(x_live, columns=feature_cols)
                with contextlib.redirect_stdout(io.StringIO()):
                    is_anomaly = if_detector.predict(df_live).iloc[0]
                if is_anomaly:
                    print_alert(flow_count, "Statistical anomaly detected in flow traffic pattern.", "Isolation Forest", severity="MEDIUM")
                    alert_counts["Isolation Forest"] += 1
                
                # 3. GraphSAGE Evaluation (suppress prints)
                x_live_scaled = (x_live - scaler_mean) / scaler_std
                X_combined = np.vstack([X_bg, x_live_scaled])
                y_combined = np.append(y_bg, [0])
                
                with contextlib.redirect_stdout(io.StringIO()):
                    graph_data = build_knn_graph(X_combined, y_combined, k=3)
                
                with torch.no_grad():
                    logits = gs_model(graph_data.x, graph_data.edge_index)
                    probs = torch.softmax(logits, dim=1)
                    new_node_pred = logits[-1].argmax().item()
                    new_node_conf = probs[-1][1].item()
                    
                    if new_node_pred == 1 and new_node_conf > 0.65:
                        print_alert(flow_count, f"Zero-Day / Unknown Attack structure detected. (Confidence: {new_node_conf*100:.1f}%)", "GraphSAGE", severity="CRITICAL")
